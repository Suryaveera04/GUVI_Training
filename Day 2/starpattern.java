public class starpattern {
    public static void main(String[] args) {
        int n = 4;
        for (int i = 1; i <= n; i++) {
            for (int j = 1; j <= i; j++) {
                int k = 0;
                k= k+1;
                k++;
                System.out.print(k);
            }
            System.out.println();
        }
    }
}